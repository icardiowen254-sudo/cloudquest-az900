import { SUBTOPIC_SLUGS, uuidV5, type ContentFile } from './content';

export interface CardContent {
  key: string;
  subtopic: string;
  front: string;
  back: string;
  example: string | null;
  reference: string;
}

export interface FlashcardFile {
  reviewed_on: string;
  note: string;
  cards: CardContent[];
}

const ALLOWED_HOSTS = ['learn.microsoft.com', 'azure.microsoft.com'];
const MIN_CARDS_PER_SUBTOPIC = 3;

export function validateFlashcards(file: FlashcardFile, questions: ContentFile): string[] {
  const problems: string[] = [];
  const add = (key: string, msg: string) => problems.push(`${key}: ${msg}`);
  const keys = new Set<string>();
  const fronts = new Set<string>();
  const perSubtopic = new Map<string, number>();

  if (file.cards.length < 30) add('file', `needs at least 30 cards, has ${file.cards.length}`);
  for (const c of file.cards) {
    if (!/^[a-z0-9-]+$/.test(c.key)) add(c.key, 'key must be lowercase letters, digits and hyphens');
    if (keys.has(c.key)) add(c.key, 'duplicate key');
    keys.add(c.key);
    if (!(SUBTOPIC_SLUGS as readonly string[]).includes(c.subtopic)) add(c.key, `unknown subtopic ${c.subtopic}`);
    if (c.front.trim().length < 8 || c.front.length > 200) add(c.key, 'front must be 8 to 200 characters');
    if (fronts.has(c.front.toLowerCase())) add(c.key, 'duplicate front');
    fronts.add(c.front.toLowerCase());
    if (c.back.trim().length < 20 || c.back.length > 400) add(c.key, 'back must be 20 to 400 characters');
    if (c.example !== null && c.example.length > 300) add(c.key, 'example is too long');
    const ref = questions.references[c.reference];
    if (!ref) {
      add(c.key, `unknown reference ${c.reference}`);
    } else {
      try {
        const url = new URL(ref.url);
        if (url.protocol !== 'https:' || !ALLOWED_HOSTS.includes(url.hostname)) add(c.key, 'reference must be https on an allowed host');
      } catch {
        add(c.key, 'reference url is invalid');
      }
    }
    perSubtopic.set(c.subtopic, (perSubtopic.get(c.subtopic) ?? 0) + 1);
  }
  for (const slug of SUBTOPIC_SLUGS) {
    if ((perSubtopic.get(slug) ?? 0) < MIN_CARDS_PER_SUBTOPIC) add('coverage', `subtopic ${slug} needs at least ${MIN_CARDS_PER_SUBTOPIC} cards`);
  }
  return problems;
}

const sql = (v: string) => `'${v.replace(/'/g, "''")}'`;
export const cardId = (key: string) => uuidV5(`flashcard:${key}`);

export function buildFlashcardSql(file: FlashcardFile, questions: ContentFile): string {
  const rows = file.cards.map((c) => {
    const example = c.example === null ? 'null' : sql(c.example);
    return `  (${sql(cardId(c.key))}, ${sql(c.subtopic)}, ${sql(c.front)}, ${sql(c.back)}, ${example}, ${sql(questions.references[c.reference].url)})`;
  });
  const ids = file.cards.map((c) => `${sql(cardId(c.key))}`).join(', ');
  return `-- GENERATED by scripts/build-seed.ts from content/flashcards.json. Do not edit by hand.
-- Reviewed ${file.reviewed_on}. ${file.cards.length} flashcards. Safe to re-run.

begin;

insert into public.flashcards (id, subtopic_id, front, back, example, reference_url, is_published)
select v.id::uuid, s.id, v.front, v.back, v.example, v.reference_url, true
from (values
${rows.join(',\n')}
) as v(id, subtopic_slug, front, back, example, reference_url)
join public.subtopics s on s.slug = v.subtopic_slug
on conflict (id) do update set
  subtopic_id = excluded.subtopic_id, front = excluded.front, back = excluded.back,
  example = excluded.example, reference_url = excluded.reference_url, is_published = true;

update public.flashcards set is_published = false
 where is_published and id <> all(array[${ids}]::uuid[]);

commit;
`;
}
