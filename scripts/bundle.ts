export interface SqlPart {
  name: string;
  sql: string;
}

const BEGIN = /^\s*begin;\s*$/i;
const COMMIT = /^\s*commit;\s*$/i;

/** Removes the transaction wrapper from one file. Fails loudly if the file is not shaped as expected. */
export function stripTransaction(part: SqlPart): string {
  const lines = part.sql.split('\n');
  const begins = lines.filter((l) => BEGIN.test(l)).length;
  const commits = lines.filter((l) => COMMIT.test(l)).length;
  if (begins !== 1 || commits !== 1) {
    throw new Error(`${part.name}: expected exactly one "begin;" and one "commit;" line, found ${begins} and ${commits}`);
  }
  return lines
    .filter((l) => !BEGIN.test(l) && !COMMIT.test(l))
    .join('\n')
    .trim();
}

/** Merges the parts, in order, into one script that runs as a single transaction. */
export function bundleSql(parts: SqlPart[]): string {
  const rule = '═'.repeat(70);
  const list = parts.map((p, i) => `--   ${i + 1}. ${p.name}`).join('\n');
  const header = `-- CloudQuest AZ-900 · complete database setup (one file)
--
-- GENERATED by scripts/build-bundle.ts. Do not edit by hand: change the source files, then run \`npm run db:bundle\`.
--
-- Paste this whole file into the Supabase SQL editor and run it ONCE on an empty project. It applies, in order:
${list}
--
-- Everything runs in ONE transaction. If any statement fails, nothing is applied, so you can fix the
-- problem and run the file again. To start over after a successful run, run supabase/reset_dev.sql first.
`;
  const body = parts
    .map((p, i) => `-- ${rule}\n-- PART ${i + 1} OF ${parts.length}: ${p.name}\n-- ${rule}\n\n${stripTransaction(p)}\n`)
    .join('\n');
  return `${header}\nbegin;\n\n${body}\ncommit;\n`;
}

